#!/usr/bin/env python3
"""Write the map-bias §30 sweep files (Plans/establishment-s30.md): establishment of the
shared form from a small share, and seed-dup with random latent tags.

    uv run python experiments/chem_tape/s30_make_sweeps.py

A start share of 1/k is k seed tapes, one shared and k-1 of the competitor, assigned in
equal shares (seed_split): with population 1024 that is 32 (1/32), 103 (1/10), 256 (1/4)
and 512 (1/2) shared genomes.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))

import shared_helper as sh  # noqa: E402

OUT = Path(__file__).resolve().parent / "sweeps" / "mapbias"
BASE = dict(task="mbs_three", disable_early_termination=True, n_examples=64, holdout_size=256,
            pop_size=1024, elite_count=2, selection_mode="lexicase", backend="numpy",
            track_lineage=False, fitness_metric="balanced", fast_rng=True, track_exact_any=False,
            dump_final_population=True, arm="TAG", mutation_rate=0.015, alphabet="tagged",
            tag_combine="leftmost", tagged_crossover="v2", track_runs=True, track_shared=True,
            seed_fraction=1.0, seed_split=True)
SEEDS = list(range(30))


def hexes(forms, L, latent="zero"):
    return ",".join(sh.form_genome(f, L, latent).tobytes().hex() for f in forms)


def establishment(name, competitor, ks, Ls, note):
    paired = [{"tape_length": L, "crossover_rate": xo, "seed_tapes": hexes(["shared"] + [competitor] * (k - 1), L)}
              for L in Ls for xo in (0.7, 0.0) for k in ks]
    spec = {"sweep_name": name, "base": {**BASE, "generations": 300, "log_every": 5},
            "paired": paired, "grid": {"seed": SEEDS}}
    hdr = (f"# Map-bias §30 (Plans/establishment-s30.md): {note}\n"
           f"# Start share of shared = 1/k for k in {ks} (one shared + k-1 {competitor} seed tapes,\n"
           f"# equal shares); crossover 0.7 and 0; L {Ls}; 300 generations; 30 seeds. Generated by\n"
           f"# experiments/chem_tape/s30_make_sweeps.py.\n")
    return hdr, spec


def main() -> int:
    files = {
        "s30_est_dup": establishment("s30_est_dup", "duplicated", [32, 10, 4, 2], [64, 128],
                                     "arm A, shared vs duplicated"),
        "s30_est_partly": establishment("s30_est_partly", "partly", [32, 10, 2], [32, 64, 128],
                                        "arm B, shared vs partly shared"),
    }
    paired = [{"tape_length": L, "crossover_rate": 0.7, "seed_tapes": hexes(["duplicated"], L, "random")}
              for L in (64, 128)]
    files["s30_dup_latent"] = (
        "# Map-bias §30 (Plans/establishment-s30.md): arm C, seed-dup with random latent tags on\n"
        "# non-RECV body cells (§29's forms carried tag 0, so an op->RECV mutation read A). L 64 and\n"
        "# 128, crossover 0.7, 1000 generations, 30 seeds. Generated by s30_make_sweeps.py.\n",
        {"sweep_name": "s30_dup_latent", "base": {**BASE, "generations": 1000, "log_every": 10},
         "paired": paired, "grid": {"seed": SEEDS}})
    for name, (hdr, spec) in files.items():
        with open(OUT / f"{name}.yaml", "w") as f:
            f.write(hdr)
            yaml.safe_dump(spec, f, sort_keys=False, width=1_000_000)
        print(name, len(spec["paired"]) * len(SEEDS), "runs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
