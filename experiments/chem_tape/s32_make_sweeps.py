#!/usr/bin/env python3
"""Write the map-bias §32 sweep files (Plans/s32-mate-latent-cases.md), Fable's programme
after the twentieth review:

- K: latent helper. Shared vs "partly shared plus an unread B run" (tags 0, 3, 1, 2; 34 cells;
     built here, not in shared_helper.FORMS), L 64, 300 generations:
     shared from 1/32 and 1/10 x crossover 0.1/0.3/0.7 (30 seeds); one shared copy at
     crossover 0 and 0.3 (100 seeds); the competitor alone at crossover 0.3 (30 seeds).
- J: who is the mate? Random starts, 3000 generations, 50 seeds: L 64 with crossover_mate
     self at 0.3 and 0.7 and random at 0.3; L 128 self at 0.3.
- L: 256 training cases, random starts, L 64, crossover 0.3, 3000 generations, 50 seeds.
- G2: §31 arm G's L 64 / 0.3 cell, seeds 50-99.

    uv run python experiments/chem_tape/s32_make_sweeps.py
"""

from __future__ import annotations

import random
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))

import shared_helper as sh  # noqa: E402
from folding_evolution.chem_tape import tagged  # noqa: E402
from s30_make_sweeps import BASE  # noqa: E402

OUT = Path(__file__).resolve().parent / "sweeps" / "mapbias"
POP = 1024
SEEDED = {**BASE, "generations": 300, "log_every": 5}
RANDOM = {**{k: v for k, v in BASE.items() if k not in ("seed_fraction", "seed_split")},
          "generations": 3000, "log_every": 20}


def partly_plus_b(L: int):
    """Partly shared form with an extra, unread B run on tag 3 (same order as the shared form)."""
    runs = [(0, sh.A_BODY), (sh.HELPER_TAG, sh.B_BODY),
            (1, [sh._recv(0)] + sh.B_BODY + sh.AND_TAIL), (2, [sh._recv(0)] + sh.B_BODY + sh.OR_TAIL)]
    return tagged.build([], [(t, tuple(sh._cells(b))) for t, b in runs], L, random.Random(L))


def write(name, hdr, base, paired, seeds):
    spec = {"sweep_name": name, "base": base, "paired": paired, "grid": {"seed": list(seeds)}}
    with open(OUT / f"{name}.yaml", "w") as f:
        f.write(hdr)
        yaml.safe_dump(spec, f, sort_keys=False, width=1_000_000)
    print(name, len(paired) * len(seeds), "runs")


def main() -> int:
    L = 64
    shared, comp = sh.form_genome("shared", L).tobytes().hex(), partly_plus_b(L).tobytes().hex()
    hdr_k = ("# Map-bias §32 arm K: shared vs partly shared plus an unread B run (tag 3), L 64, 300\n"
             "# generations. Generated by s32_make_sweeps.py.\n")
    write("s32_latent_rare", hdr_k, SEEDED,
          [{"tape_length": L, "crossover_rate": xo, "seed_tapes": ",".join([shared] + [comp] * (k - 1))}
           for xo in (0.1, 0.3, 0.7) for k in (32, 10)], range(30))
    nosplit = {k: v for k, v in SEEDED.items() if k != "seed_split"}
    write("s32_latent_copy", hdr_k, nosplit,
          [{"tape_length": L, "crossover_rate": xo, "seed_tapes": f"{shared},{comp}", "seed_counts": f"1,{POP - 1}"}
           for xo in (0.0, 0.3)], range(100))
    write("s32_latent_alone", hdr_k, SEEDED,
          [{"tape_length": L, "crossover_rate": 0.3, "seed_tapes": comp}], range(30))
    write("s32_mate",
          "# Map-bias §32 arm J: random starts with crossover_mate self / random, 3000 generations,\n"
          "# 50 seeds (compare §31 arm G, same seeds). Generated by s32_make_sweeps.py.\n",
          RANDOM,
          [{"tape_length": 64, "crossover_rate": 0.3, "crossover_mate": "self"},
           {"tape_length": 64, "crossover_rate": 0.7, "crossover_mate": "self"},
           {"tape_length": 64, "crossover_rate": 0.3, "crossover_mate": "random"},
           {"tape_length": 128, "crossover_rate": 0.3, "crossover_mate": "self"}], range(50))
    write("s32_cases256",
          "# Map-bias §32 arm L: 256 training cases, random starts, L 64, crossover 0.3, 3000\n"
          "# generations, 50 seeds. Generated by s32_make_sweeps.py.\n",
          {**RANDOM, "n_examples": 256},
          [{"tape_length": 64, "crossover_rate": 0.3}], range(50))
    write("s32_stage4_more",
          "# Map-bias §32: §31 arm G's L 64 / crossover 0.3 cell, seeds 50-99.\n",
          RANDOM, [{"tape_length": 64, "crossover_rate": 0.3}], range(50, 100))
    return 0


if __name__ == "__main__":
    sys.exit(main())
