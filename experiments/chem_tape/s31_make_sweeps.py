#!/usr/bin/env python3
"""Write the map-bias §31 sweep files (Plans/s31-dose-reciprocal-stage4.md), Fable's
programme after the nineteenth review:

- D: crossover dose 0.1 / 0.3 / 0.5, shared from 1/32 and 1/10 (seed_split, as §30)
     against duplicated (L 64) and partly shared (L 64 and 32). 300 generations, 30 seeds.
- E: reciprocal, shared at 768 / 922 / 992 of 1024 (3/4, 9/10, 31/32; seed_counts) against
     duplicated (L 64) and partly shared (L 64, 128), crossover 0.7. 300 generations, 30 seeds.
- F: 1 and 8 shared copies (seed_counts) against duplicated and partly shared, L 64,
     crossover off. 300 generations, 100 seeds.
- G: stage 4, random starts, L 32 / 64 / 128 x crossover 0.7 / 0.3 / 0. 3000 generations,
     50 seeds.

    uv run python experiments/chem_tape/s31_make_sweeps.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))

from s30_make_sweeps import BASE, hexes  # noqa: E402

OUT = Path(__file__).resolve().parent / "sweeps" / "mapbias"
POP = 1024
SEEDED = {**BASE, "generations": 300, "log_every": 5}


def write(name, hdr, base, paired, seeds):
    spec = {"sweep_name": name, "base": base, "paired": paired, "grid": {"seed": list(seeds)}}
    with open(OUT / f"{name}.yaml", "w") as f:
        f.write(hdr)
        yaml.safe_dump(spec, f, sort_keys=False, width=1_000_000)
    print(name, len(paired) * len(seeds), "runs")


def main() -> int:
    contexts = [("duplicated", 64), ("partly", 64), ("partly", 32)]
    write("s31_dose",
          "# Map-bias §31 arm D: crossover dose. Shared from 1/32 and 1/10 (one shared + k-1 competitor\n"
          "# tapes, seed_split) vs duplicated (L 64) and partly shared (L 64, 32); crossover 0.1/0.3/0.5.\n"
          "# 300 generations, 30 seeds. Generated by s31_make_sweeps.py.\n",
          SEEDED,
          [{"tape_length": L, "crossover_rate": xo, "seed_tapes": hexes(["shared"] + [comp] * (k - 1), L)}
           for comp, L in contexts for xo in (0.1, 0.3, 0.5) for k in (32, 10)],
          range(30))
    recip = [("duplicated", 64), ("partly", 64), ("partly", 128)]
    write("s31_reciprocal",
          "# Map-bias §31 arm E: reciprocal. Shared at 768/922/992 of 1024 (seed_counts) vs duplicated\n"
          "# (L 64) and partly shared (L 64, 128), crossover 0.7. 300 generations, 30 seeds.\n",
          {k: v for k, v in SEEDED.items() if k != "seed_split"},
          [{"tape_length": L, "crossover_rate": 0.7, "seed_tapes": hexes(["shared", comp], L),
            "seed_counts": f"{n},{POP - n}"} for comp, L in recip for n in (768, 922, 992)],
          range(30))
    write("s31_few_copies",
          "# Map-bias §31 arm F: 1 or 8 shared copies (seed_counts) vs duplicated and partly shared,\n"
          "# L 64, crossover off. 300 generations, 100 seeds.\n",
          {k: v for k, v in SEEDED.items() if k != "seed_split"},
          [{"tape_length": 64, "crossover_rate": 0.0, "seed_tapes": hexes(["shared", comp], 64),
            "seed_counts": f"{n},{POP - n}"} for comp in ("duplicated", "partly") for n in (1, 8)],
          range(100))
    g = {k: v for k, v in BASE.items() if k not in ("seed_fraction", "seed_split")}
    write("s31_stage4",
          "# Map-bias §31 arm G: stage 4, random starts on the three-output task. L 32/64/128 x\n"
          "# crossover 0.7/0.3/0, 3000 generations, census every 20, 50 seeds.\n",
          {**g, "generations": 3000, "log_every": 20},
          [{"tape_length": L, "crossover_rate": xo} for L in (32, 64, 128) for xo in (0.7, 0.3, 0.0)],
          range(50))
    return 0


if __name__ == "__main__":
    sys.exit(main())
